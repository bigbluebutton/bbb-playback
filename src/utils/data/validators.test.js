import {
  getLayoutSwap,
  hasProperty,
  isActive,
  isEmpty,
  isEnabled,
} from './validators';

it('checks if object has property', () => {
  const object = { property: 'value' };

  expect(hasProperty(object, 'property')).toEqual(true);
  expect(hasProperty(object, undefined)).toEqual(false);

  const missing = { property: undefined };
  expect(hasProperty(missing, 'property')).toEqual(false);
  expect(hasProperty(missing, undefined)).toEqual(false);

  const empty = {};
  expect(hasProperty(empty, 'property')).toEqual(false);
  expect(hasProperty(empty, undefined)).toEqual(false);
});

it('checks if data item is active', () => {
  // Not cleared
  expect(isActive(0.9, 1.0)).toEqual(false);
  expect(isActive(1.0, 1.0)).toEqual(true);
  expect(isActive(1.1, 1.0)).toEqual(true);

  // Cleared
  expect(isActive(1.0, 1.0, 1.1)).toEqual(true);
  expect(isActive(1.1, 1.0, 1.1)).toEqual(false);
  expect(isActive(1.2, 1.0, 1.1)).toEqual(false);
});

it('checks if data array is empty', () => {
  // Array
  expect(isEmpty([1])).toEqual(false);
  expect(isEmpty([])).toEqual(true);

  // String
  expect(isEmpty('a')).toEqual(false);
  expect(isEmpty('')).toEqual(true);

  // Invalid
  expect(isEmpty(1)).toEqual(true);
});

it('checks if data is enabled', () => {
  const data = [
    { timestamp: 1.0, clear: 2.0 },
    { timestamp: 3.0, clear: 4.0 },
  ];

  // Under
  expect(isEnabled(data, 0.0)).toEqual(false);

  // First bottom boundary
  expect(isEnabled(data, 0.9)).toEqual(false);
  expect(isEnabled(data, 1.0)).toEqual(true);

  // First top boundary
  expect(isEnabled(data, 1.9)).toEqual(true);
  expect(isEnabled(data, 2.0)).toEqual(false);

  // Second bottom boundary
  expect(isEnabled(data, 2.9)).toEqual(false);
  expect(isEnabled(data, 3.0)).toEqual(true);

  // Second top boundary
  expect(isEnabled(data, 3.9)).toEqual(true);
  expect(isEnabled(data, 4.0)).toEqual(false);

  // Above
  expect(isEnabled(data, 5.0)).toEqual(false);

  const empty = [];
  expect(isEnabled(empty, 0.0)).toEqual(false);

  const object = { timestamp: 1.2 };
  expect(isEnabled(object, 0.0)).toEqual(false);

  const missing = [{ timestamp: 1.2 }];
  expect(isEnabled(missing, 0.0)).toEqual(false);

  const invalid = [{}];
  expect(isEnabled(invalid, 0.0)).toEqual(false);
});

describe('gets the layout swap state', () => {
  // Screenshare shared from 1.0, cleared at 5.0
  const screenshare = [{ timestamp: 1.0, clear: 5.0 }];

  it('falls back to the screenshare state when layout.xml has no events', () => {
    // Recordings processed before BigBlueButton 3.0.2 have no layout.xml at all
    expect(getLayoutSwap([], screenshare, 0.0))
      .toEqual({ showPresentation: true, showScreenshare: false });
    expect(getLayoutSwap([], screenshare, 1.0))
      .toEqual({ showPresentation: true, showScreenshare: true });
    expect(getLayoutSwap([], screenshare, 5.0))
      .toEqual({ showPresentation: true, showScreenshare: false });
  });

  it('falls back to the screenshare state before the first layout event', () => {
    const layoutSwap = [{ timestamp: 3.0, showScreenshare: false }];

    expect(getLayoutSwap(layoutSwap, screenshare, 1.0))
      .toEqual({ showPresentation: true, showScreenshare: true });
    expect(getLayoutSwap(layoutSwap, screenshare, 3.0))
      .toEqual({ showPresentation: true, showScreenshare: false });
  });

  it('honors an event turning the screenshare off while it is being shared', () => {
    const layoutSwap = [{ timestamp: 0.0, showScreenshare: false }];

    expect(getLayoutSwap(layoutSwap, screenshare, 2.0))
      .toEqual({ showPresentation: true, showScreenshare: false });
  });

  it('resolves each property from its own most recent event', () => {
    // An event that only changes the presentation must not drop the screenshare
    // state back to the fallback
    const shown = [
      { timestamp: 0.0, showScreenshare: true, showPresentation: true },
      { timestamp: 6.0, showPresentation: false },
    ];

    expect(getLayoutSwap(shown, screenshare, 0.0))
      .toEqual({ showPresentation: true, showScreenshare: true });
    // At 6.0 the screenshare is no longer being shared, so the fallback would
    // resolve to false, but the 0.0 event still applies
    expect(getLayoutSwap(shown, screenshare, 6.0))
      .toEqual({ showPresentation: false, showScreenshare: true });

    const hidden = [
      { timestamp: 0.0, showScreenshare: false, showPresentation: true },
      { timestamp: 2.0, showPresentation: false },
    ];

    // At 2.0 the screenshare is being shared, so the fallback would resolve to
    // true, but the 0.0 event still applies
    expect(getLayoutSwap(hidden, screenshare, 2.0))
      .toEqual({ showPresentation: false, showScreenshare: false });
  });

  it('shows the screenshare from the start of the recording', () => {
    // Recordings generated by BigBlueButton 3.0.27 and later always carry the
    // layout state at timestamp 0
    const layoutSwap = [{ timestamp: 0.0, showScreenshare: true, showPresentation: true }];

    expect(getLayoutSwap(layoutSwap, [{ timestamp: 0.0, clear: -1 }], 0.0))
      .toEqual({ showPresentation: true, showScreenshare: true });
  });

  it('defaults the presentation to visible for events carrying show_screenshare only', () => {
    // Shape written by BigBlueButton 3.0.2 to 3.0.26
    const layoutSwap = [{ timestamp: 0.0, showScreenshare: true }];

    expect(getLayoutSwap(layoutSwap, [{ timestamp: 0.0, clear: -1 }], 0.0))
      .toEqual({ showPresentation: true, showScreenshare: true });
  });
});
